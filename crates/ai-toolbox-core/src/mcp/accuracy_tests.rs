use super::*;
use crate::testing::Fixture;
use serde_json::json;
fn context(home: &Fixture, backend: Backend) -> Context {
    if backend == Backend::Adapter {
        home.write_json(
            ".pi/agent/settings.json",
            json!({"packages":["npm:pi-mcp-adapter"]}),
        );
        home.write_json(
            ".pi/agent/npm/node_modules/pi-mcp-adapter/package.json",
            json!({"version":"5.3.0"}),
        );
    }
    let home = home.path().canonicalize().unwrap();
    Context {
        agent_dir: home.join(".pi/agent"),
        home,
        backend,
        adapter_manifest: None,
    }
}
#[test]
fn golden_hashes_match_adapter_5_3_0_not_an_invented_cache_identity() {
    // Generated by installed pi-mcp-adapter 5.3.0 computeServerHash(definition, {}).
    // No configuration loading, servers, secret commands or models were involved.
    let home = Fixture::bare();
    let ctx = context(&home, Backend::Adapter);
    for (definition, hash) in [
        (
            json!({"command":"node","args":["x.js"]}),
            "ceb46d38f51cab86b226974b788e120c307120d0be0dd0f895fdbf188e440ab1",
        ),
        (
            json!({"url":"https://example.invalid/mcp","includeTools":["read_one"]}),
            "0aba5fb6f8ec287347261f721789b36526ab7ca37a8bfa949c7a49c1f7120a58",
        ),
        (
            json!({"command":"npx","args":["-y","example"],"env":{"B":"two","A":"one"},"inheritEnv":false,"literalEnv":true}),
            "e2054092208875cff284cf8e4e9c4a46547e40ea73b2e3faa1d04ef8057deadf",
        ),
    ] {
        assert_eq!(
            super::cache::identity(&ctx, &definition).as_deref(),
            Some(hash)
        );
    }
}
#[test]
fn native_partial_overrides_do_not_change_transport_or_credentials() {
    let home = Fixture::bare();
    let repo = Fixture::bare();
    let ctx = context(&home, Backend::Native);
    home.write_json(".pi/agent/mcp.json",json!({"mcpServers":{"s":{"url":"https://example.invalid/mcp","headers":{"Authorization":"secret"},"exposure":"direct"}}}));
    repo.write_json(
        ".pi/mcp.json",
        json!({"mcpServers":{"s":{"headers":{"Authorization":"wrong"},"exposure":"deferred"}}}),
    );
    let loaded = super::config::load(&ctx, repo.path()).unwrap();
    assert_eq!(
        loaded.entries["s"].value["headers"]["Authorization"],
        "secret"
    );
    assert_eq!(
        inspect(&ctx, repo.path()).unwrap().servers[0].exposure,
        "search"
    );
}
#[test]
fn native_exact_direct_exceptions_remain_deliberate_choices() {
    let home = Fixture::bare();
    let repo = Fixture::bare();
    let ctx = context(&home, Backend::Native);
    home.write_json(".pi/agent/mcp.json",json!({"mcpServers":{"s":{"command":"never-run","exposure":"hidden","toolExposure":{"read":"direct","delete":"hidden"}}}}));
    let p = preview(&ctx, repo.path(), &[], Options::default()).unwrap();
    assert_eq!(p.changes.len(), 0);
    apply(&ctx, &p.id).unwrap();
    let loaded = super::config::load(&ctx, repo.path()).unwrap();
    assert_eq!(loaded.entries["s"].value["exposure"], "hidden");
    assert_eq!(loaded.entries["s"].value["toolExposure"]["read"], "direct");
    assert_eq!(
        loaded.entries["s"].value["toolExposure"]["delete"],
        "hidden"
    );
}
#[test]
fn an_unknown_or_legacy_adapter_cannot_claim_to_apply_a_modern_override() {
    let home = Fixture::bare();
    let repo = Fixture::bare();
    let ctx = context(&home, Backend::Adapter);
    repo.write_json(
        ".mcp.json",
        json!({"mcpServers":{"s":{"command":"never-run","directTools":true}}}),
    );
    let manifest = ".pi/agent/npm/node_modules/pi-mcp-adapter/package.json";
    std::fs::remove_file(home.path().join(manifest)).unwrap();
    assert!(preview(&ctx, repo.path(), &[], Options::default())
        .unwrap_err()
        .to_string()
        .contains("registered but not installed"));
    for version in ["2.21.2", "2.33.0"] {
        home.write_json(manifest, json!({"version":version}));
        assert!(preview(&ctx, repo.path(), &[], Options::default()).is_err());
    }
    assert!(!repo.path().join(".pi/mcp-adapter.json").exists());
}
#[test]
fn adapter_provider_auth_is_never_silently_stripped_by_project_optimisation() {
    let home = Fixture::bare();
    let repo = Fixture::bare();
    let ctx = context(&home, Backend::Adapter);
    home.write_json(".pi/agent/mcp-adapter.json",json!({"mcpServers":{"s":{"url":"https://example.invalid/mcp","auth":{"provider":"example"},"directTools":true}}}));
    let project = preview(&ctx, repo.path(), &[], Options::default()).unwrap();
    assert!(project.changes.is_empty());
    assert!(project
        .warnings
        .iter()
        .any(|w| w.contains("credential authority")));
    let p = preview(
        &ctx,
        repo.path(),
        &[repo.path().into()],
        Options {
            scope: Scope::Machine,
            ..Options::default()
        },
    )
    .unwrap();
    assert_eq!(p.changes.len(), 1);
    apply(&ctx, &p.id).unwrap();
    let loaded = super::config::load(&ctx, repo.path()).unwrap();
    assert_eq!(loaded.entries["s"].value["auth"]["provider"], "example");
}
#[test]
fn inherited_auth_material_does_not_survive_an_endpoint_replacement() {
    let home = Fixture::bare();
    let repo = Fixture::bare();
    let ctx = context(&home, Backend::Adapter);
    home.write_json(".pi/agent/mcp-adapter.json",json!({"mcpServers":{"s":{"url":"https://first.invalid/mcp","auth":{"provider":"example"},"headers":{"Authorization":"secret"},"bearerTokenStore":"private","directTools":true}}}));
    repo.write_json(
        ".mcp.json",
        json!({"mcpServers":{"s":{"url":"https://next.invalid/mcp"}}}),
    );
    let loaded = super::config::load(&ctx, repo.path()).unwrap();
    let value = &loaded.entries["s"].value;
    assert!(value.get("auth").is_none());
    assert!(value.get("headers").is_none());
    assert!(value.get("bearerTokenStore").is_none());
    assert_eq!(value["directTools"], true);
}
#[test]
fn dry_run_retains_nothing_and_external_worktrees_are_included_exactly_once() {
    let home = Fixture::bare();
    let ctx = context(&home, Backend::Adapter);
    home.write_json(
        ".pi/agent/mcp-adapter.json",
        json!({"mcpServers":{"s":{"command":"never-run","directTools":true}}}),
    );
    let lab = crate::testing::Lab::new();
    let a = lab.add_worktree("one");
    let b = lab.add_worktree("two");
    for root in [lab.main(), &a, &b] {
        std::fs::write(
            root.join(".mcp.json"),
            r#"{"mcpServers":{"s":{"directTools":true}}}"#,
        )
        .unwrap();
    }
    let roots = vec![lab.main().into(), a.clone()];
    let options = Options {
        scope: Scope::All,
        ..Options::default()
    };
    let dry = preview_read_only(&ctx, lab.main(), &roots, options.clone()).unwrap();
    assert!(!dry.retained);
    assert_eq!(dry.reports.len(), 3);
    assert!(!home.path().join(".ai-toolbox").exists());
    let saved = preview(&ctx, lab.main(), &roots, options).unwrap();
    assert_eq!(apply(&ctx, &saved.id).unwrap().files, 3);
    for root in [lab.main(), &a, &b] {
        assert_eq!(inspect(&ctx, root).unwrap().servers[0].exposure, "search");
    }
    rollback(&ctx, &saved.id).unwrap();
    for root in [lab.main(), &a, &b] {
        assert!(!root.join(".pi/mcp-adapter.json").exists());
    }
}

